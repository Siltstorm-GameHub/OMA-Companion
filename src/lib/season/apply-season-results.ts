// ============================================
// Wendet die Saison-Ergebnisse (Aktivitäts-Stufe) auf Card-Datensätze an
// ============================================
// Geändert wird nur die Aktivitäts-Stufe (und der Auto-Generiert-Marker). Klasse, Werte, Skills und
// Aussehen gehören dem Mitglied (Helden-Einrichtung) und werden von der Saison NIE angefasst. Ein in
// overriddenFields fixiertes "activityTier" bleibt ebenfalls unangetastet.

import { prisma } from "../prisma";
import { computeSeasonResults, type MemberSeasonInput } from "./season-engine";
import { ACTIVITY_TIER_RANK } from "../battle-cards/card-view";
import { dispatchNotification } from "../notify-dispatch";

const ACTIVITY_TIER_LABEL: Record<string, string> = {
  GHOST: "Geist 💤",
  NPC: "NPC 🎮",
  GAMER: "Gamer 🎖",
  LEGENDE: "Legende 🔥",
  OLD_MASTER: "Old Master 👑",
};

export async function runSeasonUpdate(members: MemberSeasonInput[]) {
  const results = computeSeasonResults(members);
  let updatedCount = 0;

  for (const result of results) {
    const card = await prisma.card.findUnique({
      where: { linkedDiscordId: members.find((m) => m.userId === result.userId)?.discordId },
    });

    if (!card) {
      console.warn(`Keine Karte für User ${result.userId} gefunden — überspringe.`);
      continue;
    }

    const tierLocked = (card.overriddenFields ?? []).includes("activityTier");
    const oldRank = ACTIVITY_TIER_RANK[card.activityTier ?? ""] ?? 0;
    const newRank = ACTIVITY_TIER_RANK[result.activityTier] ?? 0;
    const tierUpgraded = !tierLocked && newRank > oldRank;

    await prisma.card.update({
      where: { id: card.id },
      data: {
        isAutoGenerated: true,
        lastGeneratedAt: new Date(),
        ...(tierLocked ? {} : { activityTier: result.activityTier }),
      },
    });
    updatedCount++;

    if (tierUpgraded) {
      dispatchNotification("battle_card_tier_up", {
        users: [result.userId],
        placeholders: {
          "{cardName}": card.name,
          "{tier}": ACTIVITY_TIER_LABEL[result.activityTier] ?? result.activityTier,
        },
        urlOverride: "/battle-cards/my-card",
      }).catch(() => {});
    }
  }

  return { updatedCount };
}
