// ============================================
// Wendet Season-Engine-Ergebnisse auf Card-Datensätze an
// ============================================
// Felder, die in card.overriddenFields stehen, werden NIE verändert.

import { CardClass } from "@prisma/client";
import { prisma } from "../prisma";
import { computeSeasonResults, MemberSeasonInput } from "./season-engine";

// Basiswerte pro Klasse (Stufe 1) — analog zu den Standard-Karten-Werten,
// dienen als Ausgangspunkt für Community-Karten vor Anwendung des Multiplikators.
export const CLASS_BASE_STATS: Record<CardClass, { hp: number; attack: number; defense: number }> = {
  TANK: { hp: 1150, attack: 65, defense: 82 },
  DAMAGE_DEALER: { hp: 750, attack: 120, defense: 47 },
  SUPPORT: { hp: 825, attack: 42, defense: 57 },
};

/**
 * Feld darf nur geschrieben werden, wenn es NICHT in overriddenFields steht.
 */
function isOverridden(overriddenFields: string[], field: string): boolean {
  return overriddenFields.includes(field);
}

export async function runSeasonUpdate(members: MemberSeasonInput[]) {
  const results = computeSeasonResults(members);

  for (const result of results) {
    const card = await prisma.card.findUnique({
      where: { linkedDiscordId: members.find((m) => m.userId === result.userId)?.discordId },
    });

    if (!card) {
      console.warn(`Keine Karte für User ${result.userId} gefunden — überspringe.`);
      continue;
    }

    const overridden = card.overriddenFields ?? [];
    const baseStats = CLASS_BASE_STATS[result.cardClass];

    const updateData: Record<string, unknown> = {
      isAutoGenerated: true,
      lastGeneratedAt: new Date(),
    };

    if (!isOverridden(overridden, "class")) {
      updateData.class = result.cardClass;
    }
    if (!isOverridden(overridden, "activityTier")) {
      updateData.activityTier = result.activityTier;
    }
    if (!isOverridden(overridden, "baseHp")) {
      updateData.baseHp = Math.round(baseStats.hp * result.statMultiplier);
    }
    if (!isOverridden(overridden, "baseAttack")) {
      updateData.baseAttack = Math.round(baseStats.attack * result.statMultiplier);
    }
    if (!isOverridden(overridden, "baseDefense")) {
      updateData.baseDefense = Math.round(baseStats.defense * result.statMultiplier);
    }

    await prisma.card.update({
      where: { id: card.id },
      data: updateData,
    });
  }

  return { updatedCount: results.length };
}
