// ============================================
// Wendet Season-Engine-Ergebnisse auf Card-Datensätze an
// ============================================
// Felder, die in card.overriddenFields stehen, werden NIE verändert.

import { Prisma, CardClass } from "@prisma/client";
import { prisma } from "../prisma";
import { computeSeasonResults, MemberSeasonInput } from "./season-engine";
import { getSkillTemplate } from "../battle-cards/skill-templates";
import { ACTIVITY_TIER_RANK } from "../battle-cards/card-view";
import { dispatchNotification } from "../notify-dispatch";

const ACTIVITY_TIER_LABEL: Record<string, string> = {
  GHOST: "Geist 💤",
  NPC: "NPC 🎮",
  GAMER: "Gamer 🎖",
  LEGENDE: "Legende 🔥",
  OLD_MASTER: "Old Master 👑",
};

function toJson<T>(value: T): Prisma.InputJsonValue {
  return JSON.parse(JSON.stringify(value));
}

// Basiswerte pro Klasse (Stufe 1) — analog zu den Standard-Karten-Werten,
// dienen als Ausgangspunkt für Community-Karten vor Anwendung des Multiplikators.
// Angriffswerte am 2026-08-29 um +40% erhöht (gleichmäßig über alle Klassen),
// um die Kampfdauer spürbar zu verkürzen — siehe Schadensformel in damage.ts
// (Schaden = ATK − DEF×0.5, praktisch linear von ATK abhängig).
export const CLASS_BASE_STATS: Record<CardClass, { hp: number; attack: number; defense: number }> = {
  TANK: { hp: 1150, attack: 91, defense: 82 },
  DAMAGE_DEALER: { hp: 750, attack: 168, defense: 47 },
  SUPPORT: { hp: 825, attack: 59, defense: 57 },
};

/**
 * Feld darf nur geschrieben werden, wenn es NICHT in overriddenFields steht.
 */
function isOverridden(overriddenFields: string[], field: string): boolean {
  return overriddenFields.includes(field);
}

export async function runSeasonUpdate(members: MemberSeasonInput[]) {
  const results = computeSeasonResults(members);

  for (const result of results) {
    const card = await prisma.card.findUnique({
      where: { linkedDiscordId: members.find((m) => m.userId === result.userId)?.discordId },
    });

    if (!card) {
      console.warn(`Keine Karte für User ${result.userId} gefunden — überspringe.`);
      continue;
    }

    const overridden = card.overriddenFields ?? [];
    // Bei manuell fixierter Klasse gilt für Stats/Skills weiter die tatsächliche
    // (überschriebene) Klasse der Karte, nicht das neu berechnete Ergebnis.
    const effectiveClass = isOverridden(overridden, "class") ? card.class : result.cardClass;
    const baseStats = CLASS_BASE_STATS[effectiveClass];

    const updateData: Record<string, unknown> = {
      isAutoGenerated: true,
      lastGeneratedAt: new Date(),
    };

    if (!isOverridden(overridden, "class")) {
      updateData.class = result.cardClass;
    }
    let tierUpgraded = false;
    if (!isOverridden(overridden, "activityTier")) {
      updateData.activityTier = result.activityTier;
      const oldRank = ACTIVITY_TIER_RANK[card.activityTier ?? ""] ?? 0;
      const newRank = ACTIVITY_TIER_RANK[result.activityTier] ?? 0;
      tierUpgraded = newRank > oldRank;
    }
    if (!isOverridden(overridden, "baseHp")) {
      updateData.baseHp = Math.round(baseStats.hp * result.statMultiplier);
    }
    if (!isOverridden(overridden, "baseAttack")) {
      updateData.baseAttack = Math.round(baseStats.attack * result.statMultiplier);
    }
    if (!isOverridden(overridden, "baseDefense")) {
      updateData.baseDefense = Math.round(baseStats.defense * result.statMultiplier);
    }

    // Skills müssen zur (ggf. neuen) Klasse passen — sonst behält eine Karte
    // nach einem Klassenwechsel z.B. Support-Heilskills bei Tank-Stats.
    // Nutzt dieselbe Vorlage wie der Cold-Start (card-provisioning.ts).
    const skillTemplate = getSkillTemplate(effectiveClass, card.linkedDiscordId ?? card.id);
    if (!isOverridden(overridden, "passivePositive")) {
      updateData.passivePositive = toJson(skillTemplate.passivePositive);
    }
    if (!isOverridden(overridden, "passiveNegative")) {
      updateData.passiveNegative = toJson(skillTemplate.passiveNegative);
    }
    if (!isOverridden(overridden, "activeSkill")) {
      updateData.activeSkill = toJson(skillTemplate.activeSkill);
    }
    if (!isOverridden(overridden, "ultimateSkill")) {
      updateData.ultimateSkill = toJson(skillTemplate.ultimateSkill);
    }
    if (!isOverridden(overridden, "normalAttackTargetRule")) {
      updateData.normalAttackTargetRule = skillTemplate.normalAttackTargetRule;
    }

    await prisma.card.update({
      where: { id: card.id },
      data: updateData,
    });

    if (tierUpgraded) {
      dispatchNotification("battle_card_tier_up", {
        users: [result.userId],
        placeholders: {
          "{cardName}": card.name,
          "{tier}": ACTIVITY_TIER_LABEL[result.activityTier] ?? result.activityTier,
        },
        urlOverride: "/battle-cards/my-card",
      }).catch(() => {});
    }
  }

  return { updatedCount: results.length };
}
