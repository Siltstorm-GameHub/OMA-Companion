/**
 * Balancing-Check der OMA-Gems-Kampagne gegen Spieler-Teams ohne Karten-Stufen.
 *
 *   npx tsx scripts/simulate-campaign-balance.ts [kämpfe-pro-level=40] [spieler-stufe=1]
 *
 * Läuft komplett ohne Datenbank: das Spieler-Team besteht aus 5 der 6 Standard-Karten
 * (prisma/battle-cards-seed-data.ts, je Kampf zufällig gewählt), die Gegner aus den
 * Kampagnen-Leveln. Gespielt wird über dieselbe Engine wie im echten Kampf
 * (lib/battle-engine/interactive.ts), mit einem einfachen automatischen Spieler:
 *  - löst jedes bereite Ultimate sofort aus,
 *  - wählt auf dem Brett gierig den Tausch mit den meisten zerstörten Steinen.
 * Ein Mensch spielt das Brett eher besser (Kombos, Sonder-Steine), die Zahlen sind also
 * eine vorsichtige Untergrenze.
 */
import type { Card } from "@prisma/client";
import { STANDARD_CARDS } from "../prisma/battle-cards-seed-data";
import { cardToBattleUnitDefinition } from "@/lib/battle-engine/adapters";
import { advance, applyUltimateInterrupt, createInteractiveState, type InteractiveBattleState } from "@/lib/battle-engine/interactive";
import { BOARD_COLS, BOARD_ROWS, ULTIMATE_SKILL_COST } from "@/lib/battle-engine/constants";
import { resolveBoardSession, type SwapMove } from "@/lib/battle-engine/board-match3";
import { CAMPAIGN_LEVELS } from "@/lib/battle-cards/campaign-levels";
import { buildCampaignEnemyTeam, computeStars } from "@/lib/battle-cards/campaign";

const BATTLES = Number(process.argv[2] ?? 40);
const PLAYER_LEVEL = Number(process.argv[3] ?? 1);
const TEAM_SIZE = 5;

const standardCards: Card[] = STANDARD_CARDS.map((seed, i) => ({
  ...seed,
  id: `std-${i}`,
  rarity: "STANDARD",
  passivePositive: seed.passivePositive,
  passiveNegative: seed.passiveNegative,
  activeSkill: seed.activeSkill,
  ultimateSkill: seed.ultimateSkill,
  teCharacter: seed.teCharacter,
  linkedDiscordId: null,
  activityTier: null,
  sourceStatsJson: null,
  overriddenFields: [],
  isAutoGenerated: false,
  lastGeneratedAt: null,
  createdAt: new Date(),
  updatedAt: new Date(),
}) as unknown as Card);

function shuffle<T>(items: T[]): T[] {
  const out = [...items];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

function playerTeam() {
  return shuffle(standardCards).slice(0, TEAM_SIZE).map((c) => cardToBattleUnitDefinition(c, PLAYER_LEVEL));
}

/** Gieriger Brett-Zug: der Tausch mit den meisten zerstörten Steinen (Zufall bei Gleichstand). */
function bestSwap(state: InteractiveBattleState): SwapMove {
  const pending = state.pendingBoard!;
  let best: SwapMove = { fromCell: 0, toCell: 1 };
  let bestScore = -1;
  for (let cell = 0; cell < BOARD_COLS * BOARD_ROWS; cell++) {
    const neighbours = [];
    if (cell % BOARD_COLS < BOARD_COLS - 1) neighbours.push(cell + 1);
    if (cell + BOARD_COLS < BOARD_COLS * BOARD_ROWS) neighbours.push(cell + BOARD_COLS);
    for (const toCell of neighbours) {
      const swap = { fromCell: cell, toCell };
      const result = resolveBoardSession(pending.grid, pending.specials, pending.rngState, [swap], 1);
      if (result.matchedSwaps === 0) continue;
      const score = result.rawGrants.reduce((sum, g) => sum + (g.tileCount ?? 0), 0) + Math.random() * 0.5;
      if (score > bestScore) {
        bestScore = score;
        best = swap;
      }
    }
  }
  return best;
}

function fireReadyUltimates(state: InteractiveBattleState) {
  for (const unit of state.unitsA) {
    if (state.winner) return;
    if (unit.isAlive && unit.rage >= (unit.def.ultimateSkill.cost ?? ULTIMATE_SKILL_COST)) {
      applyUltimateInterrupt(state, unit.instanceId);
    }
  }
}

function simulate(levelIndex: number) {
  const level = CAMPAIGN_LEVELS[levelIndex];
  let wins = 0;
  let starSum = 0;
  let roundSum = 0;
  for (let i = 0; i < BATTLES; i++) {
    let { state, pendingDecision } = advance(createInteractiveState(playerTeam(), buildCampaignEnemyTeam(level)));
    let guard = 0;
    while (!state.winner && pendingDecision && guard++ < 500) {
      fireReadyUltimates(state);
      if (state.winner) break;
      ({ state, pendingDecision } = advance(state, { boardSwaps: [bestSwap(state)] }));
    }
    roundSum += state.round;
    if (state.winner === "A") {
      wins++;
      starSum += computeStars(state);
    }
  }
  return { level, winRate: wins / BATTLES, avgStars: wins ? starSum / wins : 0, avgRounds: roundSum / BATTLES };
}

console.log(`Kampagnen-Balancing: ${BATTLES} Kämpfe je Level, Spielerkarten Stufe ${PLAYER_LEVEL}\n`);
console.log("Level                              Siege   Ø Sterne   Ø Runden");
for (let i = 0; i < CAMPAIGN_LEVELS.length; i++) {
  const r = simulate(i);
  console.log(
    `${String(i + 1).padStart(2)}. ${r.level.name.padEnd(30)} ${(r.winRate * 100).toFixed(0).padStart(4)} %   ${r.avgStars.toFixed(1).padStart(6)}   ${r.avgRounds.toFixed(1).padStart(7)}`
  );
}
